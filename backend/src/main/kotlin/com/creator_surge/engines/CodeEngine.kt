package com.creator_surge.engines
import com.creator_surge.router.CodeArtefact
import java.io.File
class CodeEngine(private val root: File, private val base: String) {
 fun generate(prompt: String, id: String): List<CodeArtefact> {
  val dir=File(root,"code/$id").apply{mkdirs()}
  val content="""// Starter generated by Creator Surge
// Prompt: ${prompt.replace("\n"," ").take(300)}
fun main() {
    println("Hello from your Creator Surge project!")
}
"""
  val file=File(dir,"Main.kt"); file.writeText(content); val path="/outputs/code/$id/${file.name}"
  return listOf(CodeArtefact(file.name,file.absolutePath,file.name,file.absolutePath,base+path,content,"Kotlin starter source file."))
 }
}